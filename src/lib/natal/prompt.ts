/**
 * Натальный блок для системного промпта AI-таролога. Чистая сборка строки —
 * без доступа к БД, поэтому импортируется и в lib/*, и в роутах.
 * Данные карты берутся из сессии (см. src/lib/natal/context.ts).
 */
export function natalSystemBlock(summary: string | null | undefined): string | null {
  const s = (summary ?? "").trim();
  if (!s) return null;
  return `НАТАЛЬНАЯ КАРТА ЧЕЛОВЕКА (постоянный фон личности — характер, сильные и уязвимые зоны, врождённые сценарии). Учитывай её при толковании: связывай выпавшие карты и вопрос с этим фоном там, где это уместно и естественно. НЕ пересказывай карту, не превращай ответ в гороскоп, не сыпь астротерминами — вплетай выводы простым языком.

${s}`;
}
